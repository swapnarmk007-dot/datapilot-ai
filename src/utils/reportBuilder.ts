export function downloadBlob(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadCleanedCSV(data: DataRow[], filename: string) {
  const csv = Papa.unparse(data);
  downloadBlob(csv, filename, 'text/csv;charset=utf-8;');
}

/**
 * Creates and downloads a complete ZIP containing the Python Streamlit project repository!
 */
export async function downloadPythonRepositoryZip(sampleDataCsvText: string) {
  const zip = new JSZip();

  // Root files
  zip.file(
    'requirements.txt',
    `streamlit>=1.35.0
pandas>=2.2.0
numpy>=1.26.0
matplotlib>=3.8.0
seaborn>=0.13.0
scikit-learn>=1.4.0
joblib>=1.3.0
openpyxl>=3.1.0
plotly>=5.22.0
google-genai>=0.1.1
python-dotenv>=1.0.0
`
  );

  zip.file(
    '.gitignore',
    `__pycache__/
*.py[cod]
*$py.class
venv/
.env
.DS_Store
models/*.joblib
`
  );

  zip.file(
    '.env.example',
    `# GEMINI_API_KEY: Optional for AI-Powered Insights
GEMINI_API_KEY="YOUR_GEMINI_API_KEY"
`
  );

  zip.file(
    'README.md',
    `# DataPilot AI — AI-Powered Data Analysis & Machine Learning Assistant
Developed By: Swapna V
Role: Agentic AI Engineer
Organization: IPCET Solutions

## Quick Start
1. pip install -r requirements.txt
2. streamlit run app.py
`
  );

  // Data folder
  const dataFolder = zip.folder('data');
  dataFolder?.file('sample_data.csv', sampleDataCsvText);

  // Models folder
  const modelsFolder = zip.folder('models');
  modelsFolder?.file('.gitkeep', '# Serialized joblib models\n');

  // Let's fetch local module files or embed them
  try {
    const appPyRes = await fetch('/app.py');
    if (appPyRes.ok) zip.file('app.py', await appPyRes.text());
  } catch (e) {}

  const modules = [
    '__init__.py',
    'data_loader.py',
    'data_cleaning.py',
    'data_quality.py',
    'eda.py',
    'visualization.py',
    'ml_models.py',
    'prediction.py',
    'ai_insights.py',
    'report_generator.py'
  ];

  const modulesFolder = zip.folder('modules');
  for (const m of modules) {
    try {
      const res = await fetch(`/modules/${m}`);
      if (res.ok) {
        modulesFolder?.file(m, await res.text());
      }
    } catch (e) {}
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'DataPilot-AI-Streamlit-Project.zip';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
