export function buildTextReport(
  overview: DatasetOverview,
  quality: DataQualityAudit,
  cleaningActions: string[],
  mlResult: MlExperimentResult | null,
  insights: string
): string {
  const lines: string[] = [];
  lines.push('======================================================================');
  lines.push('DATAPILOT AI — EXECUTIVE DATA ANALYSIS & ML REPORT');
  lines.push('Developed By: Swapna V');
  lines.push('Role:         Agentic AI Engineer');
  lines.push('Organization: IPCET Solutions');
  lines.push('======================================================================\n');

  lines.push('1. DATASET OVERVIEW');
  lines.push('-----------------------------------');
  lines.push(`File Name:            ${overview.filename}`);
  lines.push(`Total Rows:           ${overview.rows.toLocaleString()}`);
  lines.push(`Total Columns:        ${overview.columns}`);
  lines.push(`Numerical Columns:    ${overview.numCount}`);
  lines.push(`Categorical Columns:  ${overview.catCount}`);
  lines.push(`Missing Values:       ${overview.missingValues}`);
  lines.push(`Duplicate Rows:       ${overview.duplicateRows}`);
  lines.push(`Memory Usage:         ${overview.memoryUsage}\n`);

  lines.push('2. DATA QUALITY AUDIT');
  lines.push('-----------------------------------');
  lines.push(`Data Quality Score:   ${quality.score} / 100`);
  lines.push(`Missing Values Rate:  ${quality.missingPct}%`);
  lines.push(`Duplicates Rate:      ${quality.duplicatesPct}%`);
  lines.push(`Outliers Rate:        ${quality.outliersPct}%`);
  lines.push('\nRecommendations:');
  quality.recommendations.forEach((r) => lines.push(`  • ${r}`));
  lines.push('');

  lines.push('3. DATA CLEANING AUDIT');
  lines.push('-----------------------------------');
  if (cleaningActions.length > 0) {
    cleaningActions.forEach((a) => lines.push(`  ✓ ${a}`));
  } else {
    lines.push('  No automated modifications applied.');
  }
  lines.push('');

  lines.push('4. MACHINE LEARNING & MODEL EVALUATION');
  lines.push('-----------------------------------');
  if (mlResult) {
    lines.push(`Target Feature:       ${mlResult.targetCol}`);
    lines.push(`Problem Type:         ${mlResult.problemType}`);
    lines.push(`Best Model:           ${mlResult.bestModelName}`);
    lines.push(`Performance Score:    ${mlResult.bestScoreFormatted}\n`);

    lines.push('Model Comparison Table:');
    lines.push(`${'Model'.padEnd(32)} | Score`);
    lines.push('-----------------------------------------');
    mlResult.comparisonTable.forEach((m) => {
      lines.push(`${m.model.padEnd(32)} | ${m.score}`);
    });
    lines.push('');

    if (mlResult.featureImportance.length > 0) {
      lines.push('Top Predictive Features:');
      mlResult.featureImportance.forEach((fi, idx) => {
        lines.push(`  ${idx + 1}. ${fi.feature.padEnd(24)} ${fi.importance}%`);
      });
      lines.push('');
    }
  } else {
    lines.push('No machine learning models trained yet.');
    lines.push('');
  }

  lines.push('5. AI-GENERATED BUSINESS INSIGHTS');
  lines.push('-----------------------------------');
  lines.push(insights || 'No insights generated yet.\n');

  lines.push('======================================================================');
  lines.push('Generated by DataPilot AI — Architecture by Swapna V');
  lines.push('======================================================================');

  return lines.join('\n');
}

